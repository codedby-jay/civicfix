export function getComplaint(id: string): ComplaintRecord | undefined {
  return demoComplaints.find((item) => item.id === id)
}

export function toIssuePreview(record: ComplaintRecord): CivicIssuePreview {
  return {
    id: record.id,
    title: record.title,
    category: record.category,
    severity: record.severity,
    status: record.status,
    locationLabel: record.locationLabel,
    reportedAtLabel: record.reportedAtLabel,
    x: record.x,
    y: record.y,
  }
}

export const demoMapIssues: CivicIssuePreview[] = demoComplaints
  .filter((item) => item.status !== 'resolved')
  .map(toIssuePreview)
